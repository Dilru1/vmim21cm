def cmap(name="laguna", light=0.0, dark=0.12):
    """Sequential map for "more = darker" data (r_I tables, densities): a cmastro map ("laguna" ..."""
    if name == "pastel":
        return LinearSegmentedColormap.from_list("aa:pastel", PASTEL)
    key = name.removeprefix("cmr.")
    if name in CMASTRO_SEQUENTIAL:
        rgb = CMASTRO_RGB[name][::-1]
    elif CMASHER_TYPE.get(key) == "sequential":
        rgb = CMASHER_RGB[key]
        if luminance(rgb[0]) < luminance(rgb[-1]):
            rgb = rgb[::-1]
    else:
        raise ValueError(f"cmap(): {name!r} is not a sequential cmastro/CMasher map")
    n = len(rgb)
    rgb = rgb[int(round(light * n)): n - int(round(dark * n))]
    tag = "" if (light, dark) == (0.0, 0.12) else f"[{light:g},{dark:g}]"
    return ListedColormap(rgb, name=f"aa:{key}{tag}")


