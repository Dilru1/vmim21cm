_MACHADO = {
    "deuteranopia": np.array([[0.367322, 0.860646, -0.227968],
                              [0.280085, 0.672501, 0.047413],
                              [-0.011820, 0.042940, 0.968881]]),
    "protanopia": np.array([[0.152286, 1.052583, -0.204868],
                            [0.114503, 0.786281, 0.099216],
                            [-0.003882, -0.048116, 1.051998]]),
    "tritanopia": np.array([[1.255528, -0.076749, -0.178779],
                            [-0.078411, 0.930809, 0.147602],
                            [0.004733, 0.691367, 0.303900]]),
}
CVD_KINDS = tuple(_MACHADO)


def _lin(c):
    c = np.asarray(c, float)
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def _gam(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, 12.92 * c, 1.055 * c ** (1 / 2.4) - 0.055)


def simulate_cvd(rgb, kind="deuteranopia"):
    """sRGB (..., 3) in 0..1 as seen with a full dichromacy (Machado et al. 2009)."""
    return _gam(_lin(rgb) @ _MACHADO[kind].T)


def to_lab(rgb):
    """sRGB (..., 3) in 0..1 -> CIELAB (D65)."""
    M = np.array([[0.4124564, 0.3575761, 0.1804375],
                  [0.2126729, 0.7151522, 0.0721750],
                  [0.0193339, 0.1191920, 0.9503041]])
    xyz = _lin(rgb) @ M.T / np.array([0.95047, 1.0, 1.08883])
    f = np.where(xyz > (6 / 29) ** 3, np.cbrt(xyz), xyz / (3 * (6 / 29) ** 2) + 4 / 29)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]),
                     200 * (f[..., 1] - f[..., 2])], -1)


def _de(a, b):
    return np.linalg.norm(to_lab(a) - to_lab(b), axis=-1)


def _verdict(score, thr, kind, label):
    rg = all(score[k] >= thr for k in ("deuteranopia", "protanopia"))
    cls = ("friendly" if rg and score["tritanopia"] >= thr else "red-green" if rg else "not")
    why = (f"{label} >= {thr:g}:  normal {score['normal']:.0f}  deut {score['deuteranopia']:.0f}"
           f"  prot {score['protanopia']:.0f}  trit {score['tritanopia']:.0f}")
    return dict(cls=cls, friendly=cls == "friendly", kind=kind, why=why, score=score)


def cvd_check(obj, kind=None, n=65):
    """CVD test of a map name / Colormap (kind: "sequential", "diverging", "cyclic") or of a discrete ..."""
    views = {"normal": lambda c: c, **{k: (lambda c, k=k: simulate_cvd(c, k)) for k in CVD_KINDS}}
    if isinstance(obj, (list, tuple)) and not isinstance(obj, str):
        rgb = np.array([mpl.colors.to_rgb(c) for c in obj])
        score = {}
        for v, f in views.items():
            sv = f(rgb)
            d = _de(sv[:, None], sv[None, :])
            d[np.diag_indices(len(sv))] = np.inf
            score[v] = d.min()
        return _verdict(score, 10, "discrete", "min pair dE")
    cm = get_cmap(obj)
    if kind is None:
        nm = cm.name.removeprefix("cmr.").removesuffix("_r")
        kind = CMASHER_TYPE.get(nm) or ("diverging" if nm.removeprefix("cma:") in
                                        CMASTRO_DIVERGING else "sequential")
    rgb = cm(np.linspace(0, 1, n))[:, :3]
    if kind == "sequential":
        score = {}
        for v, f in views.items():
            L = to_lab(f(rgb))[:, 0]
            sgn = np.sign(L[-1] - L[0])
            rev = np.max(np.maximum.accumulate(sgn * L) - sgn * L) if sgn else 99
            score[v] = abs(L[-1] - L[0]) if rev < 2 else 0.0
        return _verdict(score, 40, kind, "monotonic dL*")
    x = np.linspace(0.1, 0.4, 13)
    a, b = cm(x)[:, :3], cm(1 - x)[:, :3]
    score = {v: float(np.median(_de(f(a), f(b)))) for v, f in views.items()}
    return _verdict(score, 20, kind, "halves median dE")


