    out += [(f"cma:{n}", CMAPS[f"cma:{n}"], "diverging") for n in CMASTRO_DIVERGING]
    for t, names in CMASHER.items():
        out += [(f"cmr.{n}", CMAPS[f"cmr.{n}"], t) for n in names]
